def _build_banks_table_html() -> str:
    """
    WHAT: Generates an HTML table summarizing the structural differences among the three simulated banks.
    It inspects Bank entities generated by build_world, extracting customer share, weak KYC, and hold delay.
    It formats attributes into tabular ledger markup with styled numeric alignment headers.

    WHY: Visual presentation for Section 3 ('Inside the tiny world') illustrating banking sector heterogeneity.
    Proves that institutions possess distinct risk profiles and operational response characteristics.
    Tabular formatting allows quick audit verification of institutional parameters.

    Returns:
        HTML string containing complete table element detailing bank institutional properties.

    Example:
        >>> table = _build_banks_table_html()
        >>> '<table class="ledger">' in table and 'large_public' in table
        True
    """
    world = build_world(seed=101, n_people=60, n_shops=12)
    rows = []
    for b in world.banks:
        c_count = sum(1 for p in world.people if p.bank_index == b.bank_index)
        rows.append(
            f"<tr><td>Bank {b.bank_index}</td><td><code>{html.escape(b.kind)}</code></td>"
            f'<td class="num">{b.customer_share:.1%}</td><td class="num">{b.weak_kyc_share:.1%}</td>'
            f'<td class="num">{b.hold_delay_factor:.2f}x</td><td class="num">{c_count}</td></tr>'
        )
    return (
        '<table class="ledger"><thead><tr><th>Bank</th><th>Category</th><th class="num">Customer Share</th>'
        '<th class="num">Weak KYC</th><th class="num">Hold Delay</th><th class="num">Citizens</th></tr></thead>'
        f"<tbody>{''.join(rows)}</tbody></table>"
    )


