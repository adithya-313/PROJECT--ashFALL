def render_level_11_html(level_result: LevelResult) -> str:
    """
    WHAT: Renders the complete, self-contained Level 11 HTML report by substituting all 31 template variables.
    It compiles dynamic metrics, summary tables, SVG diagrams, and passbook entries into the template mapping.
    It asserts that no unpopulated placeholder tokens remain in the rendered output before returning the string.

    WHY: Produces the authoritative reports/showcase/level_11/index.html document for Level 11 showcase runs.
    Verifying that all 31 placeholders are replaced prevents broken template tokens from reaching the browser.
    Ensures complete visual excellence and rich presentation matching the project aesthetic guidelines.

    Args:
        level_result: LevelResult container holding completed execution metrics, checks, and timing numbers.

    Returns:
        Complete standalone HTML document string ready for offline browser viewing.

    Example:
        >>> from showcase.framework import LevelResult, CheckResult
        >>> cr = CheckResult("1. test", "normal", "proves x", "PASS", "ok", "", {}, None, 0.1)
        >>> lr = LevelResult(11, "title", "full", "saw", [cr], 1.0, "v1", "now", "PASSED")
        >>> html_doc = render_level_11_html(lr)
        >>> '<!DOCTYPE html>' in html_doc and 'Level 11' in html_doc
        True
    """
    template_text = TEMPLATE_PATH.read_text(encoding="utf-8")
    c3 = next((cr for cr in level_result.check_results if cr.name.startswith("3.")), None)
    c3_ev = c3.evidence if c3 else {}
    mapping = {
        **_build_scalar_tokens(level_result, c3_ev),
        **_build_html_tokens(level_result),
    }
    rendered = Template(template_text).substitute(mapping)
    assert not re.search(r"\$[A-Za-z0-9_]+", rendered), "Unpopulated template placeholders found"
    return rendered


def write_custom_page(level_result: LevelResult, out_dir: Path) -> None:
    """
    WHAT: Writes the rendered custom HTML report to disk at out_dir / index.html.
    It invokes render_level_11_html to build the full standalone page and serializes UTF-8 bytes to the output directory.
    This function serves as the custom page hook recognized and dispatched by showcase.__main__.

    WHY: Provides the custom presentation hook required by the showcase architecture for rich reporting.
    Writing the rich index.html replaces the generic framework report while preserving result.json and evidence files.
    Acting as an off switch: if this function is deleted, the runner falls back cleanly to the framework report.

    Args:
        level_result: LevelResult container holding completed execution metrics, checks, and timing numbers.
        out_dir: Filesystem path pointing to the reports/showcase/level_11 output directory.

    Returns:
        None. Writes the index.html file to disk.

    Example:
        >>> from showcase.framework import LevelResult
        >>> lr = LevelResult(11, "title", "full", "saw", [], 1.0, "v1", "now", "PASSED")
        >>> write_custom_page(lr, Path("reports/showcase/level_11"))
    """
    html_content = render_level_11_html(level_result)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "index.html").write_text(html_content, encoding="utf-8")
