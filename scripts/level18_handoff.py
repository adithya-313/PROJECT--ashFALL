"""
File: scripts/level18_handoff.py
Purpose: Write docs/handoff/level_18.md, the closing note of Level 18, from the committed console files and
amendments. It fits nothing and scores nothing.

The one input outside the repository is Run A's saved learning curve, which no console file holds.

Usage: py -3.12 -m scripts.level18_handoff
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
CONSOLE = "reports/level_18/console"
CONSOLE_FILES: tuple[str, ...] = (
    "comparison.json",
    "fallback_account.json",
    "payment_results.json",
    "calibration.json",
    "onnx_parity.json",
    "reason_codes.json",
    "leakage.json",
)
AMENDMENTS = "docs/research/amendments.md"
LEARNING_CURVE = "runs/full/run_a320/stages/learning_curve.json"
OUT = "docs/handoff/level_18.md"
KEY_AMENDMENTS: tuple[str, ...] = ("A-043", "A-063", "A-064", "A-070", "A-070a", "A-071", "A-072", "A-073")
METRICS: tuple[str, ...] = (
    "recall_at_capacity",
    "genuine_restriction_rate",
    "median_time_to_detection_hours",
    "yield_measured",
    "yield_reweighted",
)
PAYMENT_METRICS: tuple[str, ...] = (
    "truth_ap",
    "precision",
    "recall",
    "hold_rate",
    "same_bank_truth_ap",
    "other_bank_truth_ap",
)
#: Serving files the note records a digest of; the *.onnx and calibrator files are git-ignored.
FEATURE_ORDER = "config/mule_payment_feature_order.yaml"
TRITON = "serving/model_repository"
CALIBRATORS = "runs/full/level18c/calibration"
CAPACITY_LIMITATION = (
    "In these worlds both 0.25% and 0.5% capacity mean exactly 1 review per bank-day (max 172 active accounts per "
    "bank-day on test, 168 on validation); a real capacity curve needs larger worlds."
)


def amendment_change(text: str, amendment: str) -> str:
    """Return the "What changed" cell of one amendment, refusing a missing amendment or row."""
    section = re.search(rf"^## {re.escape(amendment)}\r?$(.*?)(?=^## A-|\Z)", text, re.MULTILINE | re.DOTALL)
    if section is None:
        raise ValueError(f"{AMENDMENTS}: no section for {amendment}")
    row = re.search(r"^\| What changed \| (.*?) \|\r?$", section.group(1), re.MULTILINE)
    if row is None:
        raise ValueError(f"{AMENDMENTS}: {amendment} has no 'What changed' row")
    return row.group(1)


def spread(block: dict[str, Any]) -> str:
    """Render one median with its p10 and p90."""
    return f"{block['median']:.4f} ({block['p10']:.4f} to {block['p90']:.4f})"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(root: Path = REPO_ROOT) -> str:
    """Return the note's text. A missing input file or key raises."""
    console = {name: json.loads((root / CONSOLE / name).read_text(encoding="utf-8"))["data"] for name in CONSOLE_FILES}
    amendments = (root / AMENDMENTS).read_text(encoding="utf-8")
    comparison = console["comparison.json"]
    fallback = console["fallback_account.json"]
    payment = console["payment_results.json"]
    onnx = console["onnx_parity.json"]["models"]
    codes = console["reason_codes.json"]["models"]
    calibrators = console["calibration.json"]["calibrator"]
    curve = json.loads((root / LEARNING_CURVE).read_text(encoding="utf-8"))["result"]
    leakage = {check["check"]: check for check in console["leakage.json"]["checks"]}
    six_b = leakage["check_6b"]["detail"]
    validation = fallback["serving"]["validation"]
    stress = payment["splits"]["stress"]["aggregate"]["truth_ap"]
    nan_counts = payment["splits"]["test"]["nan_reason_counts"]
    account_stress = comparison["stress"]["xgboost"]
    account_stress_numbers = "; ".join(f"{metric} {spread(account_stress[metric])}" for metric in METRICS)

    lines = [
        "# Level 18 handoff: the mule account and payment models",
        "",
        "Generated by `scripts/level18_handoff.py`. Every number is SIMULATED.",
        "",
        "## What was built",
        "",
        "Key amendments in `docs/research/amendments.md`, each with its own 'What changed' text:",
        "",
    ]
    lines.extend(f"- **{name}:** {amendment_change(amendments, name)}" for name in KEY_AMENDMENTS)
    lines.extend(
        [
            "",
            "## Served models and fallback",
            "",
            "- **Served account model:** Run A, `mule_account_xgb`, decision cut "
            f"{comparison['decision_cut']['value']!r}.",
            f"- **Served payment model:** payment {payment['version']}, `mule_payment_xgb`, threshold "
            f"{payment['threshold']!r}, hold share {payment['hold_share']}.",
            f"- **{fallback['role'].capitalize()}:** Run B, behaviour only, decision cut "
            f"{fallback['decision_cut']['value']!r}.",
            f"- **Serving choice ({fallback['serving']['amendment']}):** median validation recall at "
            f"{fallback['serving']['capacity_pct']}% capacity was "
            f"{validation['run_a']['median_recall_at_capacity']:.4f} (Run A) against "
            f"{validation['run_b']['median_recall_at_capacity']:.4f} (Run B).",
            "",
            "## Headline test numbers, median (p10 to p90)",
            "",
            f"Account models, {comparison['test_world_count']} worlds, recall at "
            f"{fallback['headline_capacity_pct']}% capacity:",
            "",
            "| metric | Run A (served) | Run B (fallback) |",
            "| --- | --- | --- |",
        ]
    )
    lines.extend(
        f"| {metric} | {spread(fallback['test']['run_a'][metric])} | {spread(fallback['test']['run_b'][metric])} |"
        for metric in METRICS
    )
    rules = comparison["test"]["rules"]["recall_at_capacity"]
    lines.extend(
        [
            "",
            f"17-3: rules baseline measured on {rules['world_count']} test worlds, recall at capacity {spread(rules)}.",
            "",
            "Payment model:",
            "",
            "| metric | test | stress |",
            "| --- | --- | --- |",
        ]
    )
    lines.extend(
        f"| {metric} | {spread(payment['splits']['test']['aggregate'][metric])} | "
        f"{spread(payment['splits']['stress']['aggregate'][metric])} |"
        for metric in PAYMENT_METRICS
    )
    points = ", ".join(
        f"{point['training_world_count']}: {point['validation_truth_average_precision']:.4f}"
        for point in curve["points"]
    )
    lines.extend(
        [
            "",
            "## Known limitations",
            "",
            f"- **Leakage check 6b (A-051):** account identifiers alone reach average precision "
            f"{six_b['average_precision_over_base_rate']:.3f} times the base rate, limit "
            f"{six_b['max_ap_over_base_rate']}. Recorded as `{leakage['check_6b']['status']}` for Run A and Run B.",
            f"- **Payment stress ranking:** stress truth AP {spread(stress)}.",
            f"- **Run A under stress** (A-073), {comparison['stress_world_count']} stress worlds, from "
            f"`{comparison['stress_source']['source']}` key `{comparison['stress_source']['key']}`: "
            f"{account_stress_numbers}.",
            "- **Run B under stress:** not run; no stress dataset was passed to it (A-070).",
            f"- **Payees at another bank:** no payee score; {nan_counts['receiver_at_other_bank']} test payments "
            "have a NaN payee risk for that reason.",
            f"- **Learning curve still rising** (Run A, training worlds: validation truth AP): {points}. "
            f"more_training_worlds_needed is {str(curve['more_training_worlds_needed']).lower()}.",
            f"- **Capacity:** {CAPACITY_LIMITATION}",
            "- **Flaky test:** `test_time_estimate_within_margin` on CI runners, GitHub issue #187.",
            "- **Open register items:** 17-1 (rule_5 recall) and 17-5 (tuned rule thresholds not committed) move to "
            "Level 19+.",
            "- **17-3:** closed in the register, covered by the multi-world rules baseline above. A-043 is about "
            "repeat-escalation counting, not coverage.",
            "",
            "## Interfaces Level 19 needs",
            "",
            "### Feature order",
            "",
            f"- Account (Run A): {codes['account']['feature_count']} features, feature sha256 "
            f"`{codes['account']['feature_sha256']}`. No standalone order file; the order is "
            "`account_model_feature_names()` in `decisions/mule_account_model.py` under the model config.",
            f"- Payment: {codes['payment']['feature_count']} features, feature sha256 "
            f"`{codes['payment']['feature_sha256']}`, file `{FEATURE_ORDER}` (file sha256 "
            f"`{_sha256(root / FEATURE_ORDER)}`).",
            "",
            "### Triton folders",
            "",
            "`model.onnx` is git-ignored, so it must be copied in on a new machine.",
            "",
            "| model | folder | config.pbtxt sha256 | console ONNX sha256 |",
            "| --- | --- | --- | --- |",
        ]
    )
    for key, model in (("account", "mule_account_xgb"), ("payment", "mule_payment_xgb")):
        lines.append(
            f"| {model} | `{TRITON}/{model}/` | `{_sha256(root / TRITON / model / 'config.pbtxt')}` | "
            f"`{onnx[key]['sha256']}` |"
        )
    lines.extend(
        [
            "",
            "The account folder's `model.onnx` (and its `config.pbtxt` comment) is the Level 18b export, sha256 "
            "`e1823d5d35b930e16344ca2fe792f04ae726a10207459c6015ee95f0db2bb4ef`, not the console's file. Compared "
            "at the Level 18 close, the two differ only in the generated ONNX graph name.",
            "",
            "### Calibrators",
            "",
        ]
    )
    lines.extend(
        f"- {key}: `{CALIBRATORS}/{block['file']}` (git-ignored), sha256 `{block['sha256']}`, {block['application']}."
        for key, block in sorted(calibrators.items())
    )
    lines.extend(
        [
            "",
            "### Account-model config switch",
            "",
            "- `config/mule_model.yaml`: `use_label_network_features` true and `rules_plus_labels_and_registry` false "
            "are the committed values.",
            "- Run A used `runs/full/run_a320_stage5c/stages/final_mule_model.yaml`; Run B used "
            "`runs/full/run_b320/stages/final_mule_model.yaml` (both git-ignored). Run B has both switches false.",
            "- `set_mule_model_config_path` in `decisions/mule_account_model.py` selects a config for a process. No "
            "automatic switch to Run B for a bank without complaint history is built.",
            "",
            "## Verify",
            "",
            "```",
            "py -3.12 -m showcase --level 18",
            "py -3.12 -B -m scripts.mule_model_quality_gate",
            "py -3.12 -m core.issue_register_v2",
            "py -3.12 -m pytest -q -p no:cacheprovider tests/unit/scripts tests/unit/showcase/test_level_18.py",
            "```",
            "",
            "## Sources",
            "",
            "| source | sha256 |",
            "| --- | --- |",
        ]
    )
    sources = [f"{CONSOLE}/{name}" for name in CONSOLE_FILES] + [AMENDMENTS, LEARNING_CURVE]
    lines.extend(f"| `{path}` | `{_sha256(root / path)}` |" for path in sources)
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the note and print its path."""
    (REPO_ROOT / OUT).write_bytes(render().encode("utf-8"))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
