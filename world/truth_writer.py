"""
WHAT: Serializes hidden truth records (roles, device control spans, transaction stories, and manifest)
to isolated JSON Lines files under a designated run directory. It also resolves the truth root directory
from environment configuration and verifies ledger account integrity and payment story coverage.

WHY: Simulation ground truth must remain completely isolated from banking feeds and model-visible outputs
(ground rules 15 and 29). Writing truth files into a dedicated directory with cryptographic manifests guarantees
auditability and tamper detection while preventing operational code from inadvertently reading simulation facts.

TERM: hidden truth: ground-truth records describing illicit roles, device controls, and payment stories,
      kept separate from bank feeds.
TERM: truth store: the file set (roles.jsonl, device_control.jsonl, payment_stories.jsonl, manifest.json)
      capturing the hidden simulation reality.
TERM: manifest: metadata file linking file names, row counts, format version, run id, and cryptographic
      SHA-256 digests.
TERM: payment story: narrative attributing a fraud payment to a gang, tactic block, layer, and description.
TERM: JSON line: a single record written as compact JSON text with sorted keys, ending in a newline.
"""

import hashlib
import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from core.config_validator import load_yaml
from world.interactive_records import InteractiveWorldOutput
from world.run_identity import REPO_ROOT
from world.truth_records import TruthFacts


def _validate_truth_accounts(output: InteractiveWorldOutput, truth: TruthFacts) -> None:
    """
    WHAT: Asserts that every account identifier referenced across role spans and device control spans
    is registered in one of the world's bank ledgers. Raises ValueError naming the missing account
    if an unregistered account identifier is encountered in either list of truth spans.

    WHY: Ground truth records must represent actual simulated entities created within the synthetic economy.
    Allowing phantom accounts in hidden truth would corrupt evaluation and attribution metrics, so all
    account identifiers must be strictly verified against the authoritative ledger account sets.

    Args:
        output: InteractiveWorldOutput container holding the simulated world with its bank ledgers.
        truth: TruthFacts container holding the role spans and device control spans to validate.

    Returns:
        None. Validation completes successfully if all account identifiers exist in the ledgers.

    Raises:
        ValueError: If any account identifier in truth spans is missing from the world's ledgers.

    Example:
        # Given a world with ledgers containing 'acc_person_000001':
        # _validate_truth_accounts(output, TruthFacts(roles=(RoleSpan('acc_person_000001', ...),)))
    """
    # 1. Collect all valid account identifiers registered in the simulated world's ledgers.
    ledger_accounts = {account for ledger in output.world.ledgers for account in ledger.accounts}

    # 2. Verify all role span accounts exist.
    for role_span in truth.roles:
        if role_span.account_id not in ledger_accounts:
            raise ValueError(
                f"Account '{role_span.account_id}' in role spans is not registered in the world's ledgers."
            )

    # 3. Verify all device control span accounts exist.
    for device_span in truth.device_control:
        if device_span.account_id not in ledger_accounts:
            raise ValueError(
                f"Account '{device_span.account_id}' in device control spans is not registered in the world's ledgers."
            )


def _build_payment_story_rows(result: Any, truth: TruthFacts) -> list[dict[str, Any]]:
    """
    WHAT: Generates sequential story dictionaries for every event in the simulation run result.
    For fraud events, it attaches gang attribution, tactic block, money layer, and narrative description
    from the indexed payment story; for planned genuine events, story attributes remain None.

    WHY: Evaluation tools require a comprehensive, event-by-event log that aligns perfectly with transaction feeds
    while explicitly annotating which events were generated by fraudulent activity versus genuine consumer actions.
    Decoupling story row generation keeps the primary row assembly logic concise and modular.

    Args:
        result: InteractiveRunResult containing event sources, payment IDs, and fraud input indices.
        truth: TruthFacts containing the payment stories configured for injected fraud payments.

    Returns:
        Ordered list of dictionary records, exactly one per simulated transaction event.

    Example:
        # For a run with 2,915 planned events and 0 fraud events:
        # story_rows = _build_payment_story_rows(output.result, TruthFacts())
        # len(story_rows) == 2915 and story_rows[0]['gang_id'] is None
    """
    # 1. Iterate through simulated events and construct one story row per event in order.
    story_rows: list[dict[str, Any]] = []
    for pos, origin in enumerate(result.event_sources):
        story = None
        if origin == "fraud":
            idx = result.event_fraud_input_index[pos]
            if idx is not None and idx < len(truth.payment_stories):
                story = truth.payment_stories[idx]
        story_rows.append({
            "block": story.block if story else None,
            "description": story.description if story else None,
            "gang_id": story.gang_id if story else None,
            "layer": story.layer if story else None,
            "origin": origin,
            "payment_id": result.payment_ids[pos],
            "planned_payment_id": result.planned_payment_ids[pos],
            "resumed": result.events_resumed[pos],
        })
    return story_rows


def build_truth_rows(
    output: InteractiveWorldOutput, truth: TruthFacts | None = None
) -> dict[str, list[dict[str, Any]]]:
    """
    WHAT: Assembles dictionaries representing records to write into roles.jsonl, device_control.jsonl,
    and payment_stories.jsonl from an interactive simulation run. Validates that all truth account IDs
    exist in the world's ledgers and that fraud events are accompanied by non-empty payment stories.

    WHY: Decouples record structuring and semantic integrity validation from disk serialization.
    Ensures that every simulated transaction event possesses a corresponding story row and that no
    illicit role or device assignment references a non-existent bank account.

    Args:
        output: InteractiveWorldOutput containing simulation ledgers, events, and identifiers.
        truth: Optional TruthFacts instance; if None, defaults to output.result.truth.

    Returns:
        Dictionary mapping artifact keys ('roles', 'device_control', 'payment_stories') to row lists.

    Raises:
        ValueError: If a truth account ID is not in ledgers or fraud events lack payment stories.

    Example:
        # For a genuine fraud-off tiny world run (2,915 events):
        # rows = build_truth_rows(output)
        # len(rows['payment_stories']) == 2915 and rows['payment_stories'][0]['gang_id'] is None
    """
    # 1. Determine active truth facts and validate account presence in world ledgers.
    active_truth = truth if truth is not None else getattr(output.result, "truth", TruthFacts())
    _validate_truth_accounts(output, active_truth)

    # 2. Reject fraud events that lack explanatory payment stories.
    result = output.result
    if any(s == "fraud" for s in result.event_sources) and len(active_truth.payment_stories) == 0:
        raise ValueError(
            "Fraud events exist in the run result but payment_stories is empty; "
            "fraud cannot be written without stories."
        )

    # 3. Format roles, device control, and sequential transaction story rows.
    roles_rows = [
        {"account_id": r.account_id, "depth": r.depth, "gang_id": r.gang_id,
         "role": r.role, "valid_from": r.valid_from, "valid_to": r.valid_to}
        for r in active_truth.roles
    ]
    dc_rows = [
        {"account_id": d.account_id, "device_id": d.device_id, "emulator": d.emulator,
         "gang_id": d.gang_id, "linked_number_switch": d.linked_number_switch,
         "remote_access": d.remote_access, "sim_swap": d.sim_swap,
         "valid_from": d.valid_from, "valid_to": d.valid_to}
        for d in active_truth.device_control
    ]
    story_rows = _build_payment_story_rows(result, active_truth)

    return {"device_control": dc_rows, "payment_stories": story_rows, "roles": roles_rows}


def _write_single_truth_file(run_dir: Path, filename: str, rows: list[dict[str, Any]]) -> dict[str, Any]:
    """
    WHAT: Writes a sequence of row dictionaries to a compact JSON Lines file in the target run directory.
    Serializes records with sorted keys, no redundant whitespace, explicit UTF-8 encoding, and standard LF newlines.
    Reads back the written file to compute its authoritative SHA-256 cryptographic digest.

    WHY: Enforces strict bit-for-bit repeatability and platform independence across all exported truth files.
    Isolating single-file serialization into a dedicated helper routine keeps the main orchestration function
    compact and adheres strictly to structural code modularity limits.

    Args:
        run_dir: Filesystem Path pointing to the active run's destination truth directory.
        filename: Base string name of the target artifact file (e.g., 'roles.jsonl').
        rows: Sequence of dictionary records to format and write as individual JSON lines.

    Returns:
        Dictionary containing the integer row count and hexadecimal SHA-256 digest string.

    Example:
        # entry = _write_single_truth_file(Path('runs/run_1'), 'roles.jsonl', [{'account_id': 'acc_1'}])
        # entry['row_count'] == 1 and len(entry['sha256']) == 64
    """
    # 1. Write compact JSON Lines to destination path.
    file_path = run_dir / filename
    with open(file_path, "w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(json.dumps(row, sort_keys=True, separators=(",", ":")) + "\n")

    # 2. Calculate cryptographic SHA-256 digest and return file summary.
    sha256 = hashlib.sha256(file_path.read_bytes()).hexdigest()
    return {"row_count": len(rows), "sha256": sha256}


def write_truth_files(
    output: InteractiveWorldOutput, truth_root: Path, truth: TruthFacts | None = None
) -> Path:
    """
    WHAT: Writes roles.jsonl, device_control.jsonl, payment_stories.jsonl, and manifest.json into a run-specific
    directory under truth_root. Refuses to overwrite non-empty existing run directories.

    WHY: Ground rule 15 requires truth to be stored as discrete, append-only file artifacts with cryptographic
    digests. Refusing non-empty folders prevents accidental corruption of previous evaluation records.

    Args:
        output: InteractiveWorldOutput holding world state, run results, and run identity.
        truth_root: Filesystem Path representing the root folder under which run truth folders are placed.
        truth: Optional TruthFacts instance overriding output.result.truth.

    Returns:
        Filesystem Path to the created run truth directory containing the truth artifacts.

    Raises:
        FileExistsError: If truth_root / run_id already exists and contains any files or directories.

    Example:
        # run_dir = write_truth_files(output, Path("runs/truth"))
        # (run_dir / "manifest.json").exists() is True
    """
    # 1. Guard against accidental overwrite by checking for existing non-empty directory.
    run_dir = truth_root / output.result.run_id
    if run_dir.exists() and any(run_dir.iterdir()):
        raise FileExistsError(
            f"Truth folder '{run_dir}' already exists and is not empty; refusing to overwrite."
        )
    run_dir.mkdir(parents=True, exist_ok=True)

    # 2. Build row dictionaries and load truth store file name configuration.
    rows_by_file = build_truth_rows(output, truth=truth)
    cfg = load_yaml(REPO_ROOT / "config" / "truth_store.yaml")["truth_store"]
    file_names = cfg["file_names"]

    # 3. Write each JSON Lines artifact and gather manifest entries.
    file_manifests = {
        file_names[key]: _write_single_truth_file(run_dir, file_names[key], rows_by_file[key])
        for key in ("roles", "device_control", "payment_stories")
    }

    # 4. Write manifest.json recording simulation metadata, code version, and file checksums.
    manifest = {
        "code_version": output.code_version,
        "files": file_manifests,
        "format": cfg["format"],
        "run_id": output.result.run_id,
    }
    manifest_path = run_dir / file_names["manifest"]
    manifest_path.write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8", newline="\n")

    return run_dir


def truth_root_from_env(env: Mapping[str, str]) -> Path:
    """
    WHAT: Resolves the truth root directory filesystem Path from a configured environment mapping.
    Raises ValueError if the variable is absent, empty, or whitespace-only.

    WHY: Ground rule 15 and task 5 mandate that truth storage paths come strictly from dedicated
    environment configuration. Refusing missing variables prevents guessing unsafe default paths.

    Args:
        env: Mapping of environment variable names to string values.

    Returns:
        Filesystem Path pointing to the configured truth root directory.

    Raises:
        ValueError: If the environment variable is not defined or contains only whitespace.

    Example:
        truth_root_from_env({"ASHFALL_TRUTH_DIR": "runs/truth"}) == Path("runs/truth")
    """
    # 1. Look up designated truth store environment variable name from policy configuration.
    cfg = load_yaml(REPO_ROOT / "config" / "truth_store.yaml")["truth_store"]
    env_var_name = cfg["env_var"]

    # 2. Extract and validate value from environment mapping.
    raw_val = env.get(env_var_name, "").strip()
    if not raw_val:
        raise ValueError(
            f"Environment variable '{env_var_name}' is missing or empty; the truth directory "
            f"location must come from the separate truth env file."
        )

    # 3. Return sanitized path as a Path object.
    return Path(raw_val)
