"""
WHAT: Empirical base rate and fraud inflation factor calculation module for Level 12h.
It computes transaction fraud shares, scales complaint densities per 100,000 successful payments,
and evaluates measured inflation factors relative to NCRP empirical benchmarks.

WHY: Level 12h requires world cards to carry measured fraud shares and empirical inflation
factors derived from national crime report registries rather than placeholder values (A-012).

TERM: base rate: Empirical real-world complaint frequency per 100,000 transactions.
TERM: fraud share: Proportion of completed payments generated by illicit fraud tactics.
TERM: fraud inflation factor: Ratio of simulation complaint density over real-world complaint rate.
"""

from pathlib import Path
from typing import Any

from core.config_validator import load_yaml

REPO_ROOT: Path = Path(__file__).resolve().parent.parent
DEFAULT_BASE_RATE_PATH: Path = REPO_ROOT / "config" / "base_rate.yaml"


def load_base_rate_config(path: Path | str | None = None) -> dict[str, Any]:
    """
    WHAT: Loads the NCRP base-rate empirical calibration configuration from config/base_rate.yaml.
    WHY: Centralizes empirical fraud benchmark rates and complaint accounting policies in YAML.
    """
    chosen = DEFAULT_BASE_RATE_PATH if path is None else Path(path)
    data = load_yaml(chosen)
    if isinstance(data, dict) and "base_rate" in data:
        return dict(data["base_rate"])
    return dict(data)


def complaints_per_100000(complaints: int, successful_payments: int) -> float:
    """
    WHAT: Computes the complaint rate scaled per 100,000 successful transactions.
    WHY: Normalizes simulation complaint volumes against the NCRP national benchmark denominator scale.
    """
    if successful_payments <= 0:
        raise ValueError(f"successful_payments {successful_payments} must be > 0")
    if complaints < 0:
        raise ValueError(f"complaints {complaints} cannot be negative")
    return (complaints / successful_payments) * 100000.0


def inflation_factor(world_ratio: float, real_ratio: float) -> float:
    """
    WHAT: Computes the fraud inflation ratio dividing the world's complaint rate by the empirical real-world rate.
    WHY: Measures how many times more dense fraud pressure is in the simulation than in authentic UPI traffic (A-012).
    """
    if real_ratio <= 0:
        raise ValueError(f"real_ratio {real_ratio} must be > 0")
    if world_ratio < 0:
        raise ValueError(f"world_ratio {world_ratio} cannot be negative")
    return world_ratio / real_ratio


def base_rate_for(
    output: Any,
    labels: list[Any] | None = None,
    config: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """
    WHAT: Computes the complete base-rate audit dictionary including fraud share and measured inflation factor.
    WHY: Populates the standardized base_rate section of world cards for fraud-on simulation environments.
    """
    cfg = load_base_rate_config() if config is None else config
    real_setting = cfg["real_world_complaints_per_100000_upi_payments"]
    real_ratio = float(real_setting["value"])
    real_source = str(real_setting["reason"])

    # 1. Resolve overall successful payments count.
    if hasattr(output.result, "run_result"):
        successful_pmts = int(output.result.run_result.counts["successes"])
        events = output.result.run_result.events
        event_sources = getattr(output.result, "event_sources", [])
    else:
        successful_pmts = int(output.result.counts["successes"])
        events = getattr(output.result, "events", [])
        event_sources = []

    # 2. Tally successful fraudulent payments and compute fraud transaction share.
    fraud_successful = sum(
        1 for ev, src in zip(events, event_sources)
        if src == "fraud" and getattr(ev, "status", "") == "success"
    )
    fraud_share = fraud_successful / successful_pmts if successful_pmts > 0 else 0.0

    # 3. Resolve complaints and evaluate true complaints.
    if labels is None:
        if hasattr(output, "effective_config"):
            from world.label_builder import build_label_events
            label_list = build_label_events(output)
        else:
            label_list = []
    else:
        label_list = labels

    total_complaints = len(label_list)
    fraud_pids = {
        pid for pid, src in zip(output.result.payment_ids, event_sources) if src == "fraud"
    } if hasattr(output.result, "payment_ids") and event_sources else set()
    true_complaints = sum(
        1 for c in label_list if any(pid in fraud_pids for pid in getattr(c, "payment_ids", ()))
    )

    # 4. Calculate rate per 100k and derive measured inflation factor.
    rate_per_100k = complaints_per_100000(total_complaints, successful_pmts)
    factor = inflation_factor(rate_per_100k, real_ratio)

    return {
        "fraud_share": fraud_share,
        "complaints": total_complaints,
        "true_complaints": true_complaints,
        "successful_payments": successful_pmts,
        "complaints_per_100000": rate_per_100k,
        "real_world_ratio": real_ratio,
        "real_world_source": real_source,
        "fraud_inflation_factor": factor,
        "note": (
            "Measured: the world's complaints per 100,000 successful payments divided by "
            "the real-world ratio (config/base_rate.yaml); a lower bound on the true inflation (A-012)."
        ),
    }
