"""
core/redaction.py

Central privacy redaction engine for logs, trace attributes, and outbox payloads.
Replaces raw simulated identifiers (account IDs, hardware device fingerprints, and
synthetic telephone numbers) with standardized '[redacted:<type>]' tokens.
"""

import re
from collections.abc import MutableMapping
from typing import Any

# Pattern 1: World Account IDs
# Matches synthetic banking account identifiers generated in the simulation, which
# uniformly begin with the 'acc_' prefix followed by alphanumeric characters or underscores
# (e.g., 'acc_person_000001', 'acc_mule_01', 'acc_shop_0042').
ACCOUNT_PATTERN: re.Pattern[str] = re.compile(r"\bacc_[A-Za-z0-9_]+\b")

# Pattern 2: Device Hardware Fingerprints
# Matches client device hardware tokens constructed in world/devices.py and tracked in
# world/device_runtime.py. Format: 'fp_<platform>_v<generation>_<token>' or 'fp_<id>'
# (e.g., 'fp_android_v3_705a5661', 'fp_ios_v5_a1b2c3d4').
FINGERPRINT_PATTERN: re.Pattern[str] = re.compile(r"\bfp_[A-Za-z0-9_]+\b")

# Pattern 3: Synthetic Phone Numbers
# Matches telecom subscriber phone numbers generated by world/phone_book.py, which
# uniformly begin with the 'sim-' prefix followed by integer digits (e.g., 'sim-0000000042').
PHONE_PATTERN: re.Pattern[str] = re.compile(r"\bsim-\d+\b")


def redact_raw_identifiers(text: str) -> str:
    """Replaces raw simulated identifiers in a string with privacy redaction tokens.

    What it is for:
        Ensures that personal and operational identifiers (bank accounts, hardware tokens,
        and phone numbers) never appear in unhashed plaintext in log files, telemetry traces,
        or inter-institutional messages.

    Inputs:
        text: Any arbitrary string that may contain raw identifiers.

    What it returns:
        Sanitized string where raw identifiers are replaced with '[redacted:<type>]'.

    How it works:
        1. Checks for non-empty string input.
        2. Applies ACCOUNT_PATTERN substitution replacing with '[redacted:account_id]'.
        3. Applies FINGERPRINT_PATTERN substitution replacing with '[redacted:fingerprint]'.
        4. Applies PHONE_PATTERN substitution replacing with '[redacted:phone_number]'.
        5. Returns the redacted string.

    Errors and side effects:
        None. Pure function with no side effects.

    Limits:
        Does not redact arbitrary numbers not matching the specific synthetic prefixes.
    """
    if not isinstance(text, str) or not text:
        return text

    sanitized = ACCOUNT_PATTERN.sub("[redacted:account_id]", text)
    sanitized = FINGERPRINT_PATTERN.sub("[redacted:fingerprint]", sanitized)
    sanitized = PHONE_PATTERN.sub("[redacted:phone_number]", sanitized)
    return sanitized


def _redact_value(value: Any) -> Any:
    """Helper to recursively sanitize nested strings, sequences, and mappings."""
    if isinstance(value, str):
        return redact_raw_identifiers(value)
    if isinstance(value, list):
        return [_redact_value(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_redact_value(item) for item in value)
    if isinstance(value, dict):
        return {k: _redact_value(v) for k, v in value.items()}
    return value


def redact_log_processor(
    logger: Any,
    method_name: str,
    event_dict: MutableMapping[str, Any],
) -> MutableMapping[str, Any]:
    """Structlog processor that redacts every string value in the log event dictionary.

    What it is for:
        Intercepts all log events emitted via structlog before serialization and strips
        out raw simulated identifiers from event messages and bound context variables.

    Inputs:
        logger: Wrapped logger instance (supplied by structlog pipeline).
        method_name: Logging method invoked (e.g. 'info', 'warning', 'error').
        event_dict: Mutable dictionary containing the log record payload.

    What it returns:
        The mutated event_dict with all string values sanitized.

    How it works:
        Iterates over all key-value entries in event_dict and applies _redact_value in-place.

    Errors and side effects:
        Modifies event_dict values in-place.
    """
    for key, val in list(event_dict.items()):
        event_dict[key] = _redact_value(val)
    return event_dict


def set_redacted_attribute(span: Any, key: str, value: Any) -> None:
    """Sets a span attribute on an OpenTelemetry span after sanitizing raw identifiers.

    What it is for:
        Provides OpenTelemetry trace attribute recording that redacts sensitive identifiers
        at the point of recording.

    Why at attribute recording time:
        In the OpenTelemetry SDK (version 1.45.0), finished span attributes are stored in an
        immutable BoundedAttributes dictionary that raises TypeError on attempted mutation
        during export. Sanitizing before span.set_attribute guarantees compliance with the
        immutable SDK API without accessing private fields.

    Inputs:
        span: OpenTelemetry Span instance (or mock/compatible span object).
        key: String attribute key (e.g. 'http.route', 'device_fingerprint').
        value: Attribute value (string, numeric, boolean, or sequence of strings).

    What it returns:
        None. Sets attribute on the span.

    How it works:
        Sanitizes string values using redact_raw_identifiers, then delegates to span.set_attribute.

    Errors and side effects:
        Mutates span attributes via span.set_attribute.
    """
    sanitized_value = _redact_value(value)
    span.set_attribute(key, sanitized_value)
