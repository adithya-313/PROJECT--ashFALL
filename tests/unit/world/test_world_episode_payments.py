def _run_single_natural_seed(seed: int, ranges: dict[str, Any], bg_config: dict[str, Any]) -> tuple[int, int]:
    """
    WHAT: Runs natural episode schedule for a single seed and verifies ledger conservation checkers.
    WHY: Encapsulates single-seed natural schedule execution to keep test_x9 within 30-line modular bounds.
    Args: seed: Random seed; ranges: Configuration dictionary; bg_config: Background device configuration.
    Returns: Tuple of (episode_count, payment_count) for the executed seed.
    Example:
        # eps, pmts = _run_single_natural_seed(101, ranges, bg_config); assert eps >= 0
    """
    # Build world and calculate aggregate opening balance across all banks.
    w = build_world(seed=seed, n_people=60, n_shops=12)
    tot_open = sum(ldg.balance_of(acc) for ldg in w.ledgers for acc in ldg.accounts)
    pr, rr = spawn_world_streams(seed)
    dr, er = spawn_life_streams(seed)
    plan = draw_world_plan(pr, n_days=61)
    # Schedule device lifecycle events and natural ordinary lifestyle episodes.
    dev_s = draw_device_event_schedule(bg_config, dr, w.people, plan.festivals, plan.n_days)
    ep_s = draw_episode_schedule(ranges, er, w.people, plan.n_days, range_name="training")
    ep_res = plan_episode_payments(w, plan, ep_s, ranges, er, range_name="training")
    # Verify planning consistency between inflows, outflows, and total candidate payment count.
    assert ep_res.report["inflows_planned"] + ep_res.report["outflows_planned"] == len(ep_res.payments)
    # Execute calendar simulation and evaluate non-negative balance and conservation checkers.
    run_world(w, plan, rr, device_events=dev_s, episode_payments=ep_res.payments)
    # Verify non-negative balance checker across bank ledgers.
    assert check_no_negative_balances(w.ledgers) == []
    # Verify entry sum balance checker.
    assert check_balances_equal_entry_sums(w.ledgers) == []
    # Verify money conservation checker.
    assert check_money_conserved(w.ledgers, tot_open) == []
    return len(ep_s), len(ep_res.payments)


