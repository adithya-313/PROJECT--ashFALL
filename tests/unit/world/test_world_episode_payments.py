def _tally_weekly_incoming(events: list[Any], account_id: str, week_start_day: int) -> tuple[int, int]:
    """
    WHAT: Tallies incoming transaction count and distinct senders for one citizen in a 7-day calendar week.
    WHY: Helper enabling X7 weekly baseline comparison before and after episode burst activity.
    Args: events: Executed event list; account_id: Account identifier; week_start_day: Starting day offset.
    Returns: Tuple of (incoming_transaction_count, distinct_sender_count).
    Example:
        # count, senders = _tally_weekly_incoming(events, 'acc_1', 0); assert count >= 0
    """
    # Convert week start day to absolute simulation minute offset.
    min_start = week_start_day * 1440
    # Compute ending simulation minute offset for the seven-day period.
    min_end = (week_start_day + 7) * 1440
    # Filter executed events to successful payments inbound to the target account.
    week_evs = [
        e for e in events
        if e.to_account == account_id and min_start <= e.minute < min_end and e.status == "success"
    ]
    return len(week_evs), len({e.from_account for e in week_evs})


