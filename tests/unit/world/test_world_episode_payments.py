def _verify_episode_flow(
    world: Any, plan: WorldPlan, ep: Episode, ranges: dict[str, Any], rng: np.random.Generator
) -> tuple[int, int, int]:
    """
    WHAT: Verifies flow invariants for one injected episode: inflow bounds, payer count, and outflow timing.
    WHY: Encapsulates structural assertion logic under 30 lines to support X3 across all 5 episode categories.
    Args: world: World container; plan: WorldPlan; ep: Injected episode; ranges: Config; rng: RNG.
    Returns: Tuple of (distinct_payers, inflow_count, outflow_count).
    Example:
        # payers, in_c, out_c = _verify_episode_flow(w, plan, ep, ranges, rng); assert in_c > 0
    """
    # Plan transactions for the target episode.
    res = plan_episode_payments(world, plan, [ep], ranges, rng, "training")
    inflows = [p for p in res.payments if p.purpose == "episode_in"]
    outflows = [p for p in res.payments if p.purpose == "episode_out"]
    payers = {p.from_account for p in inflows}
    # Check that every inflow occurs strictly within the scheduled episode interval.
    assert all(ep.start_minute <= p.minute < ep.end_minute for p in inflows)
    # Check that every outflow occurs after the scheduled episode completion time.
    assert all(p.minute >= ep.end_minute for p in outflows)
    return len(payers), len(inflows), len(outflows)


