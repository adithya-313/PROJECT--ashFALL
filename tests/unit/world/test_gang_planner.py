def test_forwarded_amount_equals_received_amount_for_every_hop(test_world) -> None:
    """
    WHAT: Asserts that every intermediate mule account forwards the exact total amount in paise that it received.
    It aggregates inflows and outflows for all intermediate accounts across multi-hop routing chains.

    WHY: Decision D7 requires intermediate mules to act strictly as transit conduits without leaking or injecting funds,
    maintaining strict money conservation across the synthetic laundering network.

    Args:
        test_world: Pytest fixture providing a simulated 30-person World instance.

    Returns:
        None. Fails if any intermediate mule forwards an amount different from what it received.

    Example:
        # for acct in intermediate_mules:
        #     assert received[acct] == forwarded[acct]
    """
    steps = (BlockStep("acquire", (("count", 4),)), BlockStep("route", (("layers", 2), ("accounts_per_layer", 2))))
    config = GangConfig("gang_flow", 2, GENEROUS_BUDGET, DEFAULT_SOURCE, steps)
    plan = plan_gang(config, test_world, np.random.default_rng(42))

    received: dict[str, int] = {}
    forwarded: dict[str, int] = {}
    for p in plan.payments:
        forwarded[p.from_account] = forwarded.get(p.from_account, 0) + p.amount_paise
        received[p.to_account] = received.get(p.to_account, 0) + p.amount_paise

    layer1_mules = {r.account_id for r in plan.truth.roles if r.depth == 1}
    for mule in layer1_mules:
        assert received[mule] == forwarded[mule]


def test_disguise_keeps_every_send_inside_dwell_window(test_world) -> None:
    """
    WHAT: Asserts that timing disguise perturbs payment dispatch minutes strictly within the holding dwell window.
    It verifies that forwarding transfers occur after funds receipt and no later than receipt plus dwell duration.

    WHY: Decision D7 models timing disguise as an evasion perturbation within the permissible dwell window;
    transfers must never dispatch before funds arrive or linger beyond the holding limit.

    Args:
        test_world: Pytest fixture providing a simulated 30-person World instance.

    Returns:
        None. Fails if any forwarding payment falls outside [receive_minute, receive_minute + dwell].

    Example:
        # assert receipt_min <= forwarding_min <= receipt_min + dwell
    """
    steps = (
        BlockStep("acquire", (("count", 2),)),
        BlockStep("route", (("layers", 2), ("accounts_per_layer", 1), ("dwell_minutes", 30))),
        BlockStep("disguise", (("jitter_minutes", 15),)),
    )
    config = GangConfig("gang_disguise", 2, GENEROUS_BUDGET, DEFAULT_SOURCE, steps)
    plan = plan_gang(config, test_world, np.random.default_rng(42))

    hop1, hop2 = plan.payments[0], plan.payments[1]
    assert hop1.to_account == hop2.from_account
    assert hop1.minute <= hop2.minute <= hop1.minute + 30


