def test_route_depths_cover_one_to_n(test_world) -> None:
    """
    WHAT: Asserts that mule accounts recruited across an N-layer routing chain receive RoleSpans with depths 1..N.
    It plans a 3-layer campaign, filters generated RoleSpan records for mule accounts, and checks depth coverage.

    WHY: Decision D7 requires forensic truth records to accurately record each mule account's hop distance
    from the collector account, enabling forensic benchmarks to measure detection capability by chain depth.

    Args:
        test_world: Pytest fixture providing a simulated 30-person World instance.

    Returns:
        None. Fails if mule depths do not span 1..N or collector depth is not None.

    Example:
        # plan = plan_gang(config, test_world, rng)
        # assert {r.depth for r in plan.truth.roles if r.role == "mule"} == {1, 2, 3}
    """
    steps = (BlockStep("acquire", (("count", 6),)), BlockStep("route", (("layers", 3), ("accounts_per_layer", 2))))
    config = GangConfig("gang_depths", 1, GENEROUS_BUDGET, DEFAULT_SOURCE, steps)
    plan = plan_gang(config, test_world, np.random.default_rng(42))

    mule_depths = {r.depth for r in plan.truth.roles if r.role == "mule"}
    assert mule_depths == {1, 2, 3}
    collector_roles = [r for r in plan.truth.roles if r.role == "collector"]
    assert len(collector_roles) == 1 and collector_roles[0].depth is None


