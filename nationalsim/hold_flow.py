"""
nationalsim/hold_flow.py

Pure algorithmic logic for 1930 administrative hold requests and inter-bank hold flow.
Provides complaint-to-hold transformation with exact-once semantics, time-of-day and
weekend hold latency formulas, four-way hold outcome classification (applied, partial,
too_late, missed), and naive one-hop forwarding decision rules under Amendment A-029.

This module is strictly decoupled: no numpy, no world/ imports, and no HTTP dependencies.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Sequence


@dataclass(frozen=True)
class HoldRequest:
    """Immutable representation of an administrative hold directive originating from a complaint.

    What it is for:
        Encapsulates the instructions sent to a receiving bank to encumber funds
        linked to reported fraudulent transactions under the 1930 reporting flow.

    Inputs:
        complaint_id: Unique identifier of the originating victim complaint (e.g., 'run-L000001').
        payment_id: Identifier of the disputed payment (e.g., '66db9aa439b092ee-000001').
        receiving_bank_index: Institutional integer index of the receiving bank (0, 1, or 2).
        account_id: Account identifier targeted for the administrative hold (e.g., 'acc_mule_01').
        amount_paise: Monetary amount to encumber in integer paise (e.g., 500000 for Rs 5,000).
        landing_minute: Simulation minute at which the hold instruction arrives at the bank.
        is_forwarded: Flag indicating whether this hold was generated by single-hop forwarding.
        originating_hold_id: Identifier of parent hold if this request is a forwarded hop, else None.

    What it returns:
        Frozen HoldRequest dataclass instance.

    How it works:
        1. Validates non-negative integer amount and minute bounds.
        2. Freezes fields to prevent modification during pipeline processing.

    Errors and side effects:
        Raises ValueError if amount_paise or landing_minute is negative.

    Limits:
        Does not interact with physical ledgers; serves as a pure message representation.
    """

    complaint_id: str
    payment_id: str
    receiving_bank_index: int
    account_id: str
    amount_paise: int
    landing_minute: int
    is_forwarded: bool = False
    originating_hold_id: str | None = None

    def __post_init__(self) -> None:
        """Validate monetary and chronological fields."""
        if self.amount_paise < 0:
            raise ValueError(f"Hold amount_paise cannot be negative, got {self.amount_paise}")
        if self.landing_minute < 0:
            raise ValueError(f"Hold landing_minute cannot be negative, got {self.landing_minute}")


@dataclass(frozen=True)
class HoldOutcome:
    """Audit record capturing the operational result of placing an administrative hold.

    What it is for:
        Records the exact financial effect of a hold at its landing minute, distinguishing
        between preservation (applied), pre-arrival fund flight (too_late), and bank inaction (missed).

    Inputs:
        status: Exactly one of 'applied', 'too_late', or 'missed'.
        held_amount_paise: Amount actually encumbered in paise (0 <= held <= requested).
        requested_amount_paise: Full amount requested by the hold directive in paise.
        account_id: Account identifier targeted by the hold.
        landing_minute: Simulation minute when the bank evaluated or attempted the hold.
        shortfall_paise: Difference between requested and held funds in paise (requested - held).

    What it returns:
        Frozen HoldOutcome dataclass instance.

    How it works:
        Stores immutable evaluation fields for downstream metrics and forwarding analysis.

    Errors and side effects:
        Raises ValueError if status is unrecognized, held amount exceeds requested, or shortfall mismatch.

    Limits:
        Evaluates point-in-time account status without mutating balances directly.
    """

    status: str
    held_amount_paise: int
    requested_amount_paise: int
    account_id: str
    landing_minute: int
    shortfall_paise: int = 0

    def __post_init__(self) -> None:
        """Validate status classification and encumbered amount bounds."""
        valid_statuses = {"applied", "too_late", "missed"}
        if self.status not in valid_statuses:
            raise ValueError(f"Invalid hold status '{self.status}': must be one of {valid_statuses}")
        if self.held_amount_paise < 0:
            raise ValueError(f"held_amount_paise cannot be negative, got {self.held_amount_paise}")
        if self.held_amount_paise > self.requested_amount_paise:
            raise ValueError(
                f"held_amount_paise ({self.held_amount_paise}) cannot exceed "
                f"requested_amount_paise ({self.requested_amount_paise})"
            )
        expected_shortfall = self.requested_amount_paise - self.held_amount_paise
        if self.shortfall_paise == 0 and expected_shortfall != 0:
            object.__setattr__(self, "shortfall_paise", expected_shortfall)
        elif self.shortfall_paise != expected_shortfall:
            raise ValueError(
                f"shortfall_paise ({self.shortfall_paise}) does not equal "
                f"requested ({self.requested_amount_paise}) - held ({self.held_amount_paise})"
            )


@dataclass
class OutgoingTransfer:
    """Record of funds leaving an account prior to a hold's arrival.

    What it is for:
        Supplies financial transfer metadata to the naive one-hop forwarding engine
        when evaluating downstream money routing after partial or too-late hold landing.

    Inputs:
        transfer_id: Unique payment or transfer identifier.
        from_account: Originating debtor account identifier.
        to_account: Creditor account identifier that received the departed funds.
        to_bank_index: Bank index of the receiving creditor account.
        amount_paise: Departed monetary amount in integer paise.
        minute: Simulation minute when the outgoing transfer posted.

    What it returns:
        Mutable or frozen OutgoingTransfer dataclass instance.

    How it works:
        Encapsulates ledger departure metadata for downstream forwarding inspection.

    Errors and side effects:
        None.

    Limits:
        Represents single-transaction transfer facts within the sending institution.
    """

    transfer_id: str
    from_account: str
    to_account: str
    to_bank_index: int
    amount_paise: int
    minute: int


class HoldFlowTracker:
    """Manages hold request emission with strict exact-once complaint idempotency.

    What it is for:
        Guarantees that each victim complaint converts into at most one administrative hold.
        Duplicate submissions with the same complaint_id are safely ignored.

    Inputs:
        None.

    What it returns:
        Initialized HoldFlowTracker instance with empty seen complaint tracking.

    How it works:
        1. Checks internal seen set for complaint_id.
        2. If already registered, returns None to ensure idempotent execution.
        3. If fresh, records complaint_id and constructs a new HoldRequest.

    Errors and side effects:
        Maintains an internal set of registered complaint identifiers.

    Limits:
        In-memory idempotency tracking scoped to the tracker's lifecycle.
    """

    def __init__(self) -> None:
        """Initialize empty complaint registration tracking."""
        self.seen_complaints: set[str] = set()

    def create_hold_request(
        self,
        complaint_id: str,
        payment_id: str,
        receiving_bank_index: int,
        account_id: str,
        amount_paise: int,
        landing_minute: int,
        is_forwarded: bool = False,
        originating_hold_id: str | None = None,
    ) -> HoldRequest | None:
        """Create a new HoldRequest if the complaint has not been processed yet.

        What it is for:
            Enforces exactly-once hold creation per complaint identifier.

        Inputs:
            complaint_id: Unique complaint identifier string.
            payment_id: Identifier of the disputed transaction.
            receiving_bank_index: Destination bank index.
            account_id: Destination account identifier.
            amount_paise: Monetary amount to hold in paise.
            landing_minute: Arrival simulation minute.
            is_forwarded: Whether this hold is a forwarded second-hop request.
            originating_hold_id: Optional parent hold identifier.

        What it returns:
            HoldRequest instance if complaint is newly seen, or None if already processed.

        How it works:
            1. Check if complaint_id is already in seen_complaints.
            2. If seen, return None immediately.
            3. If not seen, add to seen_complaints and return newly constructed HoldRequest.

        Errors and side effects:
            Appends complaint_id to internal tracking set.

        Limits:
            Returns None on duplicates without raising an exception.
        """
        if complaint_id in self.seen_complaints:
            # Enforce exact-once semantics: drop duplicates silently
            return None

        self.seen_complaints.add(complaint_id)
        return HoldRequest(
            complaint_id=complaint_id,
            payment_id=payment_id,
            receiving_bank_index=receiving_bank_index,
            account_id=account_id,
            amount_paise=amount_paise,
            landing_minute=landing_minute,
            is_forwarded=is_forwarded,
            originating_hold_id=originating_hold_id,
        )


def is_night_hour(hour: int, night_hours: tuple[int, int] | Sequence[int]) -> bool:
    """Determine whether a clock hour falls inside the configured off-hours window.

    What it is for:
        Identifies whether a given hour (0..23) is subject to night-time latency scaling.

    Inputs:
        hour: Integer clock hour (0 to 23).
        night_hours: 2-element sequence [start_hour, end_hour] defining the off-hours window.
            For example, (22, 6) denotes 22:00 to 06:00 IST.

    What it returns:
        True if the hour lies inside the night interval, False otherwise.

    How it works:
        1. Extract start and end boundaries.
        2. If start > end (wraps across midnight), check if hour >= start or hour < end.
        3. If start <= end (single-day window), check if start <= hour < end.

    Errors and side effects:
        Raises ValueError if hour is outside [0, 23].

    Limits:
        Operates on integer clock hours.
    """
    if not (0 <= hour <= 23):
        raise ValueError(f"Clock hour must be between 0 and 23, got {hour}")
    start, end = night_hours[0], night_hours[1]
    if start > end:
        return hour >= start or hour < end
    return start <= hour < end


def compute_hold_latency(
    base_latency_minutes: float,
    bank_hold_delay_factor: float,
    arrival_dt: datetime,
    night_hours: tuple[int, int] | Sequence[int],
    night_multiplier: float,
    weekend_multiplier: float,
    u_unreachable: float,
    unreachable_share: float,
    unreachable_extra_delay_minutes: float,
) -> int:
    """Calculate the operational latency in minutes before a hold lands at the receiving bank.

    What it is for:
        Implements the composite latency equation specified in Amendment A-029:
        latency = (base * bank_factor * time_of_day * weekend) + unreachable_delay.

    Inputs:
        base_latency_minutes: Raw drawn delay in minutes from world ranges.
        bank_hold_delay_factor: Bank institutional response multiplier.
        arrival_dt: Timezone-aware IST datetime when the complaint/hold is lodged.
        night_hours: 2-element sequence specifying night start and end clock hours.
        night_multiplier: Multiplier applied during night hours (e.g., 2.0).
        weekend_multiplier: Multiplier applied on Saturdays and Sundays (e.g., 1.5).
        u_unreachable: Uniform random draw in [0, 1) determining reporting line access.
        unreachable_share: Probability threshold for victim reporting line congestion.
        unreachable_extra_delay_minutes: Extra waiting delay if victim was unreachable.

    What it returns:
        Integer elapsed minutes between complaint filing and hold landing.

    How it works:
        1. Evaluate time-of-day multiplier using arrival_dt.hour and night_hours.
        2. Evaluate weekend multiplier using arrival_dt.weekday() (5=Saturday, 6=Sunday).
        3. Scale base latency by bank factor and applicable temporal multipliers.
        4. Add unreachable extra delay only when u_unreachable < unreachable_share.
        5. Round total latency to the nearest integer minute.

    Errors and side effects:
        Raises ValueError if base latency, bank factor, or multipliers are negative.

    Limits:
        Evaluates temporal multipliers against the moment of arrival.
    """
    if base_latency_minutes < 0:
        raise ValueError(f"base_latency_minutes cannot be negative, got {base_latency_minutes}")
    if bank_hold_delay_factor <= 0:
        raise ValueError(f"bank_hold_delay_factor must be positive, got {bank_hold_delay_factor}")

    # 1. Determine time-of-day scaling factor
    time_mult = night_multiplier if is_night_hour(arrival_dt.hour, night_hours) else 1.0

    # 2. Determine weekend scaling factor (weekday 5 is Saturday, 6 is Sunday)
    is_weekend = arrival_dt.weekday() >= 5
    wknd_mult = weekend_multiplier if is_weekend else 1.0

    # 3. Compute base institutional processing latency
    operational_delay = base_latency_minutes * bank_hold_delay_factor * time_mult * wknd_mult

    # 4. Add congestion delay only if uniform draw indicates caller failed to reach 1930
    extra_delay = unreachable_extra_delay_minutes if u_unreachable < unreachable_share else 0.0

    # 5. Round final composite duration to nearest integer simulation minute
    return int(round(operational_delay + extra_delay))


def classify_hold_outcome(
    available_balance_paise: int,
    requested_amount_paise: int,
    account_id: str,
    landing_minute: int,
    missed: bool,
) -> HoldOutcome:
    """Classify the execution outcome of an administrative hold directive at its landing minute.

    What it is for:
        Exhaustively categorizes the hold result into one of three mutually exclusive states:
        'applied', 'too_late', or 'missed' under Amendment A-029 and Round 2 specification.
        A hold finding some money but less than requested is 'applied' with shortfall_paise > 0.

    Inputs:
        available_balance_paise: Total balance present in the account at landing minute.
        requested_amount_paise: Monetary amount demanded by the hold directive in paise.
        account_id: Account identifier targeted by the hold directive.
        landing_minute: Simulation minute when the bank evaluates the hold.
        missed: Boolean indicating whether the bank failed to act due to administrative omission.

    What it returns:
        HoldOutcome audit record with status, held amount, and shortfall in paise.

    How it works:
        1. If missed is True, bank never acted: status is 'missed', held is 0, shortfall is requested.
        2. If available balance >= requested amount: full hold, status is 'applied', held is requested, shortfall is 0.
        3. If available balance <= 0: all funds departed, status is 'too_late', held is 0, shortfall is requested.
        4. If 0 < available balance < requested: partly-funded hold, status is 'applied', held is available balance,
           shortfall is requested minus available balance.

    Errors and side effects:
        Raises ValueError if requested_amount_paise <= 0.

    Limits:
        Does not debit or lock account directly; reports audit classification only.
    """
    if requested_amount_paise <= 0:
        raise ValueError(f"requested_amount_paise must be positive, got {requested_amount_paise}")

    if missed:
        # Bank operational inaction: directive was ignored and no lien placed
        return HoldOutcome(
            status="missed",
            held_amount_paise=0,
            requested_amount_paise=requested_amount_paise,
            account_id=account_id,
            landing_minute=landing_minute,
            shortfall_paise=requested_amount_paise,
        )

    if available_balance_paise >= requested_amount_paise:
        # Sufficient funds: entire requested amount is encumbered without shortfall
        return HoldOutcome(
            status="applied",
            held_amount_paise=requested_amount_paise,
            requested_amount_paise=requested_amount_paise,
            account_id=account_id,
            landing_minute=landing_minute,
            shortfall_paise=0,
        )

    if available_balance_paise <= 0:
        # Zero funds remaining: money moved out before hold arrived
        return HoldOutcome(
            status="too_late",
            held_amount_paise=0,
            requested_amount_paise=requested_amount_paise,
            account_id=account_id,
            landing_minute=landing_minute,
            shortfall_paise=requested_amount_paise,
        )

    # Partly-funded funds present: hold encumbers whatever money remains with shortfall
    return HoldOutcome(
        status="applied",
        held_amount_paise=available_balance_paise,
        requested_amount_paise=requested_amount_paise,
        account_id=account_id,
        landing_minute=landing_minute,
        shortfall_paise=requested_amount_paise - available_balance_paise,
    )


def decide_one_hop_forwarding(
    original_hold: HoldRequest,
    outcome: HoldOutcome,
    outgoing_transfers: Sequence[OutgoingTransfer],
) -> HoldRequest | None:
    """Evaluate naive single-hop forwarding for funds that departed prior to hold landing.

    What it is for:
        Implements baseline single-hop traceback: when a hold arrives too late or partially,
        the receiving bank inspects its own internal ledger for outgoing transfers that
        carried the money away and emits exactly one forwarded hold directive to the next bank.

    Inputs:
        original_hold: The primary HoldRequest evaluated by the institution.
        outcome: The HoldOutcome classification produced at landing minute.
        outgoing_transfers: Chronological list of transfers departing this account before landing.

    What it returns:
        A new HoldRequest targeting the recipient of the departed funds, or None if no forward occurs.

    How it works:
        1. If original_hold is already a forwarded request, stop immediately (exactly one hop).
        2. If outcome is 'applied' (all funds held) or 'missed' (bank did not act), return None.
        3. If outcome is 'too_late' or 'partial', calculate unencumbered departed amount.
        4. Inspect outgoing_transfers that posted prior to original_hold.landing_minute.
        5. If eligible outgoing transfers exist, select the latest transfer and construct
           a new HoldRequest with is_forwarded=True and originating_hold_id set.
        6. If no outgoing transfers exist, return None.

    Errors and side effects:
        None.

    Limits:
        Inspects only the receiving bank's own internal ledger; stops after strictly one hop.
    """
    # 1. Enforce strict single-hop boundary: never forward a request that is already forwarded
    if original_hold.is_forwarded:
        return None

    # 2. If the bank never acted, no forward directive is generated
    if outcome.status == "missed":
        return None

    # 3. Calculate how much money departed before the hold could freeze it
    unheld_paise = outcome.requested_amount_paise - outcome.held_amount_paise
    if unheld_paise <= 0:
        return None

    # 4. Filter for transfers that posted before the hold landed
    eligible = [t for t in outgoing_transfers if t.minute <= original_hold.landing_minute]
    if not eligible:
        return None

    # 5. Pick the most recent departed transfer carrying the flight of funds
    latest_transfer = max(eligible, key=lambda t: t.minute)

    # 6. Target the departed amount up to the payment amount
    forward_amount_paise = min(unheld_paise, latest_transfer.amount_paise)

    return HoldRequest(
        complaint_id=f"fwd-{original_hold.complaint_id}",
        payment_id=latest_transfer.transfer_id,
        receiving_bank_index=latest_transfer.to_bank_index,
        account_id=latest_transfer.to_account,
        amount_paise=forward_amount_paise,
        landing_minute=original_hold.landing_minute,  # Base moment before second-hop latency calculation
        is_forwarded=True,
        originating_hold_id=original_hold.complaint_id,
    )
